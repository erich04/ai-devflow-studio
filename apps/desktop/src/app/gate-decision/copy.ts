import { blockingTargetLabels } from '../node-inspector-view-model'
export type GateKind = 'requirement' | 'design'
/** 需求 / 方案. */
export const noun = (kind: GateKind) => (kind === 'requirement' ? '需求' : '方案')
/** "需求 v2", "方案 v1", or the recorded-time label of a design without a number. */
export const versionLabel = (kind: GateKind, number: number | undefined, recordedAt?: string) =>
  number === undefined ? `${noun(kind)}（记录于 ${recordedAt ?? '未知时间'}）` : `${noun(kind)} v${number}`
/** The next version: "需求 v3"; a design without a number gets "新版方案". */
export const nextVersionLabel = (kind: GateKind, number: number | undefined) =>
  number === undefined ? `新版${noun(kind)}` : `${noun(kind)} v${number + 1}`
export const roleLabel = (role: RequiredGateRole | string | undefined) =>
  role === 'owner' ? 'Owner' : role === 'lead' ? 'Lead' : role === 'member' ? 'Member' : role ?? 'Member'
export const policyTargetLabel = (target: GateEnforcementReason['target']) => blockingTargetLabels[target]
