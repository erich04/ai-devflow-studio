import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { clearContentDigestCacheForTests } from '../../app/useContentDigest'
import {
  buildF1, buildF1RevisionPending, buildF3, listFor, nodeIdsOf, policyDecision, policyReason, type GateFixture,
} from '../../testing/gate-fixtures'
import { gateActionSpies, gateFacts, GateHarness, storeRevisionLists } from '../../testing/gate-page'

beforeEach(() => { clearContentDigestCacheForTests(); localStorage.clear() })
afterEach(() => { cleanup(); vi.useRealTimers(); vi.restoreAllMocks() })
const bar = () => screen.getByTestId('gate-decision-bar')
const barButton = (name: string) => within(bar()).getByRole('button', { name })
const withoutReview = (fixture: GateFixture): GateFixture => {
  const { review: _review, ...rest } = fixture
  return { ...rest, reviews: [] }
}

describe('GateDecisionBar', () => {
  it('renders row 7a without buttons and with a disabled toggle before the digest is known', async () => {
    const fixture = await buildF1()
    render(<GateHarness fixture={fixture} spies={gateActionSpies()} facts={gateFacts()} />)
    expect(bar()).toHaveAttribute('data-row', '7a')
    expect(within(bar()).getByText('正在核对审查与当前正文的对应关系…')).toBeInTheDocument()
    expect(bar().querySelector('.gate-bar-buttons')).toBeNull()
    const toggle = within(bar()).getByRole('button', { name: /修订清单/ })
    expect(toggle).toBeDisabled()
    expect(toggle).toHaveTextContent(/^修订清单 ▾$/)
    await waitFor(() => expect(bar()).toHaveAttribute('data-row', '15'))
  })
  it('shows the buttons of the row with primary first and the cost line beside 「审查需求 v1」 (amendment 33)', async () => {
    const spies = gateActionSpies()
    render(<GateHarness fixture={withoutReview(await buildF1())} spies={spies} facts={gateFacts()} />)
    const review = await waitFor(() => barButton('审查需求 v1'))
    const confirm = barButton('确认需求 v1')
    expect(confirm).toHaveClass('primary-button')
    expect(review).toHaveClass('ghost-button')
    const actions = review.closest('.gate-bar-actions') as HTMLElement
    expect(within(actions).getByText('将用 Fake · fake-model 审查需求 v1，可能产生费用')).toBeInTheDocument()
    fireEvent.click(within(actions).getByRole('button', { name: '更换审查模型' }))
    expect(spies.onOpenModelSettings).toHaveBeenCalledTimes(1)
    fireEvent.click(review)
    expect(spies.onRequestReview).toHaveBeenCalledTimes(1)
  })
  it('asks once before confirming without a review (row 14) and confirms on the second click', async () => {
    const spies = gateActionSpies()
    const facts = gateFacts({ policy: { decision: policyDecision({ warningReasons: [policyReason('missing_agent_review')] }), isLoading: false, enabled: true, teamBinding: true } })
    render(<GateHarness fixture={withoutReview(await buildF1())} spies={spies} facts={facts} />)
    const confirm = await waitFor(() => barButton('确认需求 v1'))
    expect(barButton('审查需求 v1')).toHaveClass('primary-button')
    fireEvent.click(confirm)
    expect(spies.onConfirm).not.toHaveBeenCalled()
    expect(within(bar()).getByRole('status')).toHaveTextContent('还没有审查需求 v1，本次确认针对需求 v1。再次点击「确认需求 v1」提交。')
    fireEvent.click(confirm)
    expect(spies.onConfirm).toHaveBeenCalledWith(expect.objectContaining({ unsubmittedCount: 0, current: expect.objectContaining({ id: 'gate-run-clarification-v1' }) }))
  })
  it('shows 「停止」 for a running review and passes its target', async () => {
    const spies = gateActionSpies()
    render(<GateHarness fixture={await buildF1()} spies={spies} facts={gateFacts({ runFacts: { reviewRunning: true, generationRunning: false, writeLock: false } })} />)
    expect(bar()).toHaveAttribute('data-row', '5')
    fireEvent.click(barButton('停止'))
    expect(spies.onStop).toHaveBeenCalledWith('review')
  })
  it('bumps the toggle without expanding when an item is added, and 「第 K 项」 opens the list', async () => {
    render(<GateHarness fixture={await buildF1()} spies={gateActionSpies()} facts={gateFacts()} />)
    const card = await screen.findByRole('article', { name: '意见 2 · 重要' })
    vi.useFakeTimers()
    fireEvent.click(within(card).getByRole('button', { name: '采纳' }))
    const toggle = within(bar()).getByRole('button', { name: /修订清单 1 项/ })
    expect(toggle).toHaveClass('is-bumped')
    expect(toggle).toHaveAttribute('aria-expanded', 'false')
    expect(bar().querySelector('.gate-list-panel')).toBeNull()
    act(() => { vi.advanceTimersByTime(1_700) })
    expect(toggle).not.toHaveClass('is-bumped')
    fireEvent.click(within(card).getByRole('button', { name: '已加入修订清单（第 1 项）' }))
    expect(toggle).toHaveAttribute('aria-expanded', 'true')
    const item = bar().querySelector('[data-item-id]')!
    expect(item).toHaveClass('is-flashing')
    expect(item).toHaveTextContent('来自意见 2')
  })
  it('shows the panel texts and validates an own item', async () => {
    render(<GateHarness fixture={await buildF1()} spies={gateActionSpies()} facts={gateFacts()} />)
    await waitFor(() => expect(bar()).toHaveAttribute('data-row', '15'))
    fireEvent.click(within(bar()).getByRole('button', { name: /修订清单 0 项/ }))
    const panel = within(bar()).getByRole('region', { name: '对需求 v1 的修改 · 提交后生成 v2' })
    expect(within(panel).getByText('还没有修改。采纳审查意见、回答待确认问题，或点「＋ 添加其他修改」；右侧答疑里的建议也可以加入。')).toBeInTheDocument()
    fireEvent.click(within(panel).getByRole('button', { name: '＋ 添加其他修改' }))
    const input = within(panel).getByRole('textbox', { name: '其他修改' })
    expect(input).toHaveAttribute('placeholder', '例如：在验收标准里补一条失败时的提示')
    fireEvent.click(within(panel).getByRole('button', { name: '加入修订清单' }))
    expect(within(panel).getByRole('alert')).toHaveTextContent('请写下要修改的内容。')
    fireEvent.change(input, { target: { value: '长'.repeat(1001) } })
    fireEvent.click(within(panel).getByRole('button', { name: '加入修订清单' }))
    expect(within(panel).getByRole('alert')).toHaveTextContent('最多 1000 字，现在 1001 字。')
    fireEvent.change(input, { target: { value: '补一条多个关键词的验收标准。' } })
    fireEvent.click(within(panel).getByRole('button', { name: '加入修订清单' }))
    expect(within(panel).getByText('我添加的')).toBeInTheDocument()
    expect(within(panel).getByText('补一条多个关键词的验收标准。')).toBeInTheDocument()
    expect(within(bar()).getByRole('button', { name: '提交修订，生成 v2（1 项）' })).toHaveClass('primary-button')
    expect(within(panel).getByText('将用 Direct Provider · fake-model 生成，可能产生费用')).toBeInTheDocument()
  })
  it('submits the composed text of the list', async () => {
    const fixture = await buildF1()
    storeRevisionLists([await listFor(fixture.current, [{ type: 'addOwn', text: '补一条失败提示。' }])])
    const spies = gateActionSpies()
    render(<GateHarness fixture={fixture} spies={spies} facts={gateFacts()} />)
    fireEvent.click(await waitFor(() => barButton('提交修订，生成 v2（1 项）')))
    expect(spies.onSubmit).toHaveBeenCalledWith(expect.objectContaining({ itemCount: 1, proposals: [],
      text: '修订清单（共 1 项，针对需求 v1）：\n1. 我添加的：补一条失败提示。', target: expect.objectContaining({ kind: 'requirement', artifactId: fixture.current.id }) }))
  })
  it('shows the old-list notice with a link that opens the older version', async () => {
    const f3 = await buildF3()
    const fixture = { ...f3, artifacts: f3.artifacts.filter((artifact) => artifact.kind !== 'clarification_feedback') }
    storeRevisionLists([await listFor(f3.previous!, [{ type: 'addOwn', text: '旧版本上的修改。' }])])
    const spies = gateActionSpies()
    render(<GateHarness fixture={fixture} spies={spies} facts={gateFacts()} />)
    const note = await within(bar()).findByText('需求已更新为 v2。你在需求 v1 上的修订清单（1 项）没有提交。')
    fireEvent.click(within(note.parentElement!).getByRole('button', { name: '查看需求 v1 的清单' }))
    expect(spies.onOpenVersion).toHaveBeenCalledWith(f3.previous!.id)
  })
  it('「重新读取」 calls onReloadPolicy and shows no confirm button (row 8a)', async () => {
    const spies = gateActionSpies()
    render(<GateHarness fixture={await buildF1()} spies={spies} facts={gateFacts({ policy: { decision: null, isLoading: false, loadError: 'policy read failed', enabled: true, teamBinding: true } })} />)
    fireEvent.click(await waitFor(() => barButton('重新读取')))
    expect(spies.onReloadPolicy).toHaveBeenCalledTimes(1)
    expect(within(bar()).queryByRole('button', { name: '确认需求 v1' })).toBeNull()
    expect(within(bar()).getByText('状态待核实：读取审批条件失败，暂时无法判断能否确认。', { selector: 'span' })).toBeInTheDocument()
  })
  it('「重新核对」 retries the failed digest', async () => {
    const fixture = await buildF1()
    const digest = vi.spyOn(globalThis.crypto.subtle, 'digest').mockRejectedValueOnce(new Error('digest unavailable'))
    render(<GateHarness fixture={fixture} spies={gateActionSpies()} facts={gateFacts()} />)
    const recheck = await waitFor(() => barButton('重新核对'))
    expect(bar()).toHaveAttribute('data-row', '7b')
    expect(within(bar()).queryByRole('button', { name: '确认需求 v1' })).toBeNull()
    fireEvent.click(recheck)
    await waitFor(() => expect(bar()).toHaveAttribute('data-row', '15'))
    expect(digest.mock.calls.length).toBeGreaterThan(1)
  })
  it('a note with the settings link opens model settings (row 4 without a model)', async () => {
    const fixture = await buildF1RevisionPending()
    const spies = gateActionSpies()
    render(<GateHarness fixture={fixture} nodeId={nodeIdsOf().clarify} spies={spies}
      facts={gateFacts({ generation: { executorLabel: 'Direct Provider', modelSelected: false } })} />)
    const regenerate = await waitFor(() => barButton('重新生成需求 v2'))
    expect(regenerate).toBeDisabled()
    expect(regenerate).toHaveAttribute('aria-description', '还没有选择生成使用的模型，请在设置行的「更改」里选择。')
    const note = within(bar()).getByText('还没有选择生成使用的模型，请在设置行的「更改」里选择。', { selector: 'span' }).parentElement!
    fireEvent.click(within(note).getByRole('button', { name: '打开模型与执行方式设置' }))
    expect(spies.onOpenModelSettings).toHaveBeenCalledTimes(1)
    fireEvent.click(within(bar()).getByRole('button', { name: '更改' }))
    expect(within(bar()).getByText('执行方式与模型选择')).toBeInTheDocument()
  })
  it('「返回需求 v2」 calls showCurrentVersion and nothing else', async () => {
    const fixture = await buildF3()
    const spies = gateActionSpies()
    render(<GateHarness fixture={fixture} readingArtifactId={fixture.previous!.id} spies={spies} facts={gateFacts()} />)
    const back = await waitFor(() => barButton('返回需求 v2'))
    expect(back).toHaveClass('primary-button')
    expect(within(bar()).getByText('需求 v2 · 你的决定')).toBeInTheDocument()
    for (const name of ['确认需求 v2', '审查需求 v2']) expect(within(bar()).queryByRole('button', { name })).toBeNull()
    fireEvent.click(back)
    expect(spies.showCurrentVersion).toHaveBeenCalledTimes(1)
    for (const [name, spy] of Object.entries(spies)) if (name !== 'showCurrentVersion' && name !== 'renderStageSettings') expect(spy, name).not.toHaveBeenCalled()
  })
})
