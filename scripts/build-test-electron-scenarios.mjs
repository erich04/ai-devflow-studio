import { expect } from '@playwright/test'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { scanFirstLayerText } from '../apps/desktop/src/app/first-layer-scan.ts'

export async function runBuildTestScenario({ page, run, buildNode, project, modelRequests, repositoryPath, testCounterPath }) {
  const output = path.resolve(process.env.DEVFLOW_BUILD_TEST_OUTPUT ?? 'output/playwright/build-test-electron')
  await mkdir(output, { recursive: true })
  const errors = [], steps = []
  const record = async name => { const current = page.getByTestId('gate-decision-bar'); steps.push({ name, decision: await current.count() ? await current.getAttribute('data-row') : null }) }
  page.on('pageerror', error => errors.push(error.message))
  const history = () => page.evaluate(runId => window.aiDevFlowDesktop.getCodingChangeHistory({ runId }), run.id)
  const state = () => page.evaluate(() => window.aiDevFlowDesktop.loadState())
  const bar = page.getByTestId('gate-decision-bar')
  const scan = async () => {
    const prose = await page.locator('[data-first-layer]').evaluateAll(roots => roots.filter(root => !root.parentElement?.closest('[data-first-layer]')).map(root => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
      const text = []
      while (walker.nextNode()) {
        const el = walker.currentNode.parentElement
        if (!el?.checkVisibility() || el.closest('[data-raw-material]') || el.closest('details:not([open])') && !el.closest('summary')) continue
        text.push(walker.currentNode.textContent)
      }
      return text.join(' ')
    }).join('\n'))
    expect(scanFirstLayerText(prose, ['deepseek-v4-flash'])).toEqual([])
  }
  try {
    await page.setViewportSize({ width: 1440, height: 900 })
    await page.reload()
    await page.getByRole('navigation', { name: '六阶段导航' }).getByRole('button', { name: /开发实现/ }).click()
    await expect(bar.getByRole('button', { name: '开始开发', exact: true })).toBeEnabled()
    await bar.getByRole('button', { name: '开始开发', exact: true }).click()
    await expect(bar).toContainText('改动 v1 · 你的决定', { timeout: 30_000 })
    await expect.poll(async () => (await history()).reviews.at(-1)?.status).toBe('completed')
    const inspector = page.getByTestId('node-inspector')
    await inspector.getByRole('tab', { name: '材料与版本', exact: true }).click()
    await inspector.getByRole('button', { name: '改动 v1 · 待批准', exact: true }).click()
    await page.getByRole('button', { name: '答疑', exact: true }).click()
    await expect(bar.getByRole('button', { name: '批准改动 v1，进入测试', exact: true })).toBeEnabled()
    const material = page.getByTestId('build-test-material')
    await expect(material).toContainText('message = "new"')
    const workspace = page.locator('.build-test-workspace')
    await expect(workspace).toHaveAttribute('data-layout', 'wide')
    const finding = page.locator('.gate-margin [data-card-id^="finding:"]')
    await expect(finding).toContainText('消息文字还可以更明确')
    const geometry = await workspace.evaluate(el => {
      const m = el.querySelector('[data-testid="build-test-material"]').getBoundingClientRect()
      const c = el.querySelector('[data-card-id^="finding:"]').getBoundingClientRect()
      return { workspace: el.getBoundingClientRect().width, material: m.width, card: c.width, overflow: el.scrollWidth - el.clientWidth }
    })
    expect(geometry.material).toBeGreaterThanOrEqual(520)
    expect(geometry.card).toBeGreaterThanOrEqual(240)
    expect(geometry.overflow).toBeLessThanOrEqual(1)
    await scan(); await record('initial change and completed self-check at 1440')
    await page.screenshot({ path: path.join(output, '01-change-wide.png'), fullPage: true })
    await page.setViewportSize({ width: 1200, height: 900 })
    await expect(workspace).toHaveAttribute('data-layout', 'narrow')
    await page.getByRole('button', { name: /意见 1/ }).first().click()
    await expect(page.getByRole('button', { name: '采纳', exact: true })).toBeVisible()
    await scan(); await record('narrow finding popover at 1200')
    const narrow = await workspace.evaluate(el => ({ workspace: el.getBoundingClientRect().width, layout: el.getAttribute('data-layout'), overflow: el.scrollWidth - el.clientWidth }))
    expect(narrow.overflow).toBeLessThanOrEqual(1)
    await page.screenshot({ path: path.join(output, '02-change-narrow.png'), fullPage: true })
    await page.getByRole('button', { name: '采纳', exact: true }).click()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: /意见 1/ }).first()).toBeFocused()
    await bar.getByRole('button', { name: '按清单修改，生成改动 v2（1 项）', exact: true }).click()
    await expect(bar).toContainText('改动 v2 · 你的决定', { timeout: 30_000 })
    await expect.poll(async () => (await history()).reviews.at(-1)?.status).toBe('completed')
    const revised = await history()
    expect(revised.changeSets).toHaveLength(2)
    expect(revised.changeSets[1].revision.previous.id).toBe(revised.changeSets[0].id)
    expect(revised.changeSets[1].codingRunId).toBe(revised.changeSets[0].codingRunId)
    expect(revised.changeSets[1].view.files[0].rows.some(row => row.isNew)).toBe(true)
    await expect(material).toContainText('message = "revised"'); await record('revision stays on the original coding run')
    await workspace.locator('.artifact-reading-tools > summary').click()
    await workspace.getByLabel('阅读改动或测试报告').selectOption(revised.changeSets[0].id)
    await expect(bar.getByRole('button', { name: /批准/ })).toHaveCount(0)
    await expect(material).toContainText('message = "new"'); await record('history is read only')
    await bar.getByRole('button', { name: '返回改动 v2', exact: true }).click()
    await page.setViewportSize({ width: 1440, height: 900 })
    await bar.getByRole('button', { name: '批准改动 v2，进入测试', exact: true }).click()
    await expect(bar).toContainText('改动 v3（修复） · 你的决定', { timeout: 30_000 })
    await expect(material).toContainText('message = "fixed"')
    await expect(material).toContainText('第 1 次测试报告')
    await scan(); await record('failed test and pending automatic repair')
    await page.screenshot({ path: path.join(output, '03-repair.png'), fullPage: true })
    await bar.getByRole('button', { name: '批准修复，重新测试', exact: true }).click()
    await expect(bar.getByRole('button', { name: '确认测试证据，进入 PR 交付', exact: true })).toBeEnabled({ timeout: 30_000 })
    await expect(material).toContainText('第 2 次测试报告')
    await record('approved repair passes the second test')
    const passed = await state()
    const coding = passed.codingRuns.find(c => c.runId === run.id)
    expect(coding.status).toBe('completed')
    const managed = passed.managedCodingWorkspaces.find(w => w.id === coding.managedWorkspaceId)
    expect(await readFile(path.join(managed.worktreePath, 'src/message.js'), 'utf8')).toBe('export const message = "fixed"\n')
    expect(await readFile(path.join(repositoryPath, 'src/message.js'), 'utf8')).toBe('export const message = "old"\n')
    // The report becomes invalid when its exact worktree changes, and valid again after restoration.
    await writeFile(path.join(managed.worktreePath, 'src/message.js'), 'export const message = "tampered"\n')
    await expect(bar).toContainText('测试证据已过期', { timeout: 20_000 })
    await expect(bar.getByRole('button', { name: '确认测试证据，进入 PR 交付', exact: true })).toBeDisabled(); await record('tampered worktree blocks stale evidence')
    await writeFile(path.join(managed.worktreePath, 'src/message.js'), 'export const message = "fixed"\n')
    await expect(bar.getByRole('button', { name: '确认测试证据，进入 PR 交付', exact: true })).toBeEnabled({ timeout: 20_000 })
    const beforeConfirm = await state(), calls = modelRequests.length
    const testsBefore = Number(await readFile(testCounterPath, 'utf8'))
    expect(testsBefore).toBe(2)
    await scan()
    await page.screenshot({ path: path.join(output, '04-evidence.png'), fullPage: true })
    await bar.getByRole('button', { name: '确认测试证据，进入 PR 交付', exact: true }).click()
    await expect.poll(async () => (await state()).runs.find(r => r.id === run.id)?.nodes.find(n => n.stage === 'test')?.status).toBe('success')
    const afterConfirm = await state()
    expect(modelRequests).toHaveLength(calls)
    const testsAfter = Number(await readFile(testCounterPath, 'utf8'))
    expect(testsAfter).toBe(testsBefore)
    await record('confirmation reuses evidence without executing another test or model call')
    expect(afterConfirm.codingRuns).toEqual(beforeConfirm.codingRuns)
    const priorEvidence = beforeConfirm.testEvidence.filter(e => e.runId === run.id).at(-1)
    const confirmed = afterConfirm.testEvidence.filter(e => e.runId === run.id).at(-1)
    expect(afterConfirm.testEvidence).toHaveLength(beforeConfirm.testEvidence.length + 1)
    expect(confirmed.reusedFrom.evidenceId).toBe(priorEvidence.id)
    expect(confirmed.sourceTree.digest).toBe(priorEvidence.sourceTree.digest)
    expect(confirmed.command).toBe(priorEvidence.command)
    const storedRun = afterConfirm.runs.find(r => r.id === run.id)
    expect(storedRun.nodes.find(n => n.id === storedRun.currentNodeId)?.stage).toBe('pr')
    expect(errors).toEqual([])
    await writeFile(path.join(output, 'evidence.json'), JSON.stringify({ steps, geometry, narrow, viewportSizes: [1440, 1200], testCommandCounts: { beforeConfirmation: testsBefore, afterConfirmation: testsAfter }, providerRequests: modelRequests.length, externalProviderCalled: false, firstLayerScan: 'passed at both widths and repair/evidence states', phases: modelRequests.map(r => { try { return JSON.parse(r.messages[1].content).phase } catch { return undefined } }).filter(Boolean), codingRunId: coding.id, sourceUnchanged: true, revisionSameRun: true, staleEvidenceBlocked: true, confirmationMadeNoModelCall: true, pageErrors: errors }, null, 2))
    console.log('Build/test Electron smoke passed: wide/narrow review, revision, immutable history, failed test, repair approval, stale evidence, and explicit confirmation with no extra model call.')
  } catch (error) {
    await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true }).catch(() => undefined)
    await writeFile(path.join(output, 'failure-dom.txt'), await page.locator('body').innerText()).catch(() => undefined)
    throw error
  }
}
